    public static long GetLocationIdByName(string name)
    {
        var idx = LocationIds.BinarySearch(name, StringComparer.Ordinal);
        if (idx < 0)
        {
            Melon<LwnApMod>.Logger.Error($"GetLocationIdByName failed to find location \"{name}\"!");
            return -1;
        }
        else
        {
            Melon<LwnApMod>.Logger.Msg($"GetLocationIdByName mapped \"{name}\" to ({idx + 1})");
            return idx + 1;
        }
    }
